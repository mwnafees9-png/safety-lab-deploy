// build-standalone.mjs — bundles the modular sources into ONE self-contained
// HTML file (rams-lab-standalone.html) that runs from a double-click (file://).
// The modular sources stay canonical; this is a mechanical transform:
//   - strip import lines (everything shares one scope in the bundle)
//   - strip `export ` keywords
//   - wrap each module file in an IIFE that registers itself
// Run: node build-standalone.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), 'site');
const read = p => readFileSync(join(ROOT, p), 'utf8');

function strip(src) {
    return src
        .split('\n')
        .filter(l => !/^\s*import\s/.test(l))
        .join('\n')
        .replace(/^export\s+\{[^}]*\};?\s*$/gm, '')
        .replace(/\bexport\s+(const|function|async function|let|class)\b/g, '$1');
}

const CORE = ['core/bus.js', 'core/store.js', 'core/evidence.js', 'core/engine.js', 'core/registry.js', 'spine/en50126.js', 'ui/shell.js']
    .map(p => '// ===== ' + p + ' =====\n' + strip(read(p))).join('\n\n');

const MODULES = ['modules/dashboard.js', 'modules/sample.js', 'modules/hazards.js', 'modules/thr.js',
    'modules/reliability.js', 'modules/availability.js', 'modules/maintainability.js',
    'modules/sracs.js', 'modules/safetycase.js']
    .map(p => '// ===== ' + p + ' =====\n(() => {\n' + strip(read(p)) + '\nregistry.register(module);\n})();').join('\n\n');

const css = read('rams.css');

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>RAMS Lab — EN 50126 RAMS Assessment Workspace (standalone)</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500;600&display=swap" rel="stylesheet">
<style>
${css}
</style>
</head>
<body>
<script>
'use strict';
// RAMS Lab standalone bundle — generated by build-standalone.mjs from the
// modular sources in site/. Do not edit by hand; edit the modules and rebuild.
${CORE}

${MODULES}

// ===== composition (app.js equivalent) =====
shell.mount(document.body, { spine });
</script>
</body>
</html>`;

const out = join(dirname(fileURLToPath(import.meta.url)), 'rams-lab-standalone.html');
writeFileSync(out, html);
console.log('wrote', out, '(' + html.length + ' bytes)');

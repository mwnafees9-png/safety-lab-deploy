const MCP_INSTRUCTIONS = "Safety Lab holds an aircraft program's safety analysis: functions, failure conditions, fault trees, requirements, assumptions and the traces between them. You can read all of it. You can propose functions, requirements and assumptions with propose_items; proposals are staged and enter the analysis only when an engineer accepts them in Safety Lab and signs. Fault trees, safety requirements and every number are produced by Safety Lab's deterministic engine and cannot be written from here. Each item says who owns it; an item another tool owns is changed in that tool.";

async function mcpCall(env, deps, client, name, args) {
  args = (args && typeof args === "object") ? args : {};
  const projects = await projectsFor(env, deps, client);
  if (name === "list_projects") return { projects: projects.map((p) => drop({ id: p.id, name: p.name, certificationBasis: p.cert_basis, canPropose: p.can_send })) };
  const project = projects.filter((p) => p.id === S(args.project))[0];
  if (!project) throw new McpError("No project with that id is open to this key. Call list_projects for the ids.");
  const lim = (rows) => { const limit = Math.max(1, Math.min(500, Number(args.limit) || 100)), offset = Math.max(0, Number(args.offset) || 0); return { total: rows.length, offset, returned: Math.min(limit, Math.max(0, rows.length - offset)), items: rows.slice(offset, offset + limit) }; };
  if (name === "list_collections" || name === "get_proposal_status" || name === "propose_items") {
    if (name === "list_collections") {
      const cols = arr(await sbJson(deps, env, "/api_collections?project_id=eq." + enc(project.id) + "&client=eq." + enc(client.id) + "&select=*&order=name.asc"));
      return { collections: cols.map(collectionOut) };
    }
    const cname = S(args.collection);
    if (name === "get_proposal_status") {
      const col = await getCollection(env, deps, project.id, client, cname);
      if (!col) throw new McpError("No collection " + cname + " for this key in this project.");
      const rows = (await allItems(env, deps, col.id)).filter((r) => !r.removed_at).map(itemOut);
      const tally = { waiting: 0, accepted: 0, rejected: 0, sentBySafetyLab: 0 };
      rows.forEach((r) => { if (r.origin === "safety-lab") tally.sentBySafetyLab++; else tally[r.status] = (tally[r.status] || 0) + 1; });
      return Object.assign({ collection: collectionOut(col), tally }, lim(rows));
    }
    if (!project.can_send) throw new McpError("This key reads but does not propose. Ask a workspace admin for a key that can send.");
    if (TOOL_KINDS.indexOf(S(args.kind)) < 0) throw new McpError("kind is one of " + TOOL_KINDS.join(", ") + ". Failure conditions and fault trees are made in Safety Lab.");
    const pc = await putCollection(env, deps, project.id, client, cname, { kind: S(args.kind) });
    if (pc.res) throw new McpError((await pc.res.json()).error.message);
    const w = await writeItems(env, deps, project, client, pc.col, arr(args.items), false);
    if (w.res) throw new McpError((await w.res.json()).error.message);
    return w.out;
  }
  const d = await loadDoc(env, deps, project.id);
  const head = { project: { id: project.id, name: project.name, version: d.version } };
  if (name === "get_project") return Object.assign(head.project, { canPropose: project.can_send }, viewSummary(d.doc), { name: project.name });
  if (name === "list_functions") return Object.assign(head, lim(viewFunctions(d.doc, args.scope)));
  if (name === "list_failure_conditions") { const sev = S(args.severity).toLowerCase(); return Object.assign(head, lim(viewFailureConditions(d.doc, args.scope).filter((r) => !sev || S(r.severity).toLowerCase() === sev))); }
  if (name === "list_requirements") return Object.assign(head, lim(viewRequirements(d.doc, args.scope)));
  if (name === "list_assumptions") return Object.assign(head, lim(viewAssumptions(d.doc, args.scope)));
  if (name === "list_fault_trees") return Object.assign(head, lim(viewFaultTrees(d.doc, args.scope)));
  if (name === "get_fault_tree") { const t = viewFaultTree(d.doc, S(args.tree), Number(args.depth) || 6); if (!t) throw new McpError("No fault tree with that id. Call list_fault_trees for the ids."); return Object.assign(head, t); }
  if (name === "get_traces") { const it = S(args.item); return Object.assign(head, lim(viewTraces(d.doc, args.scope).filter((t) => !it || t.from.id === it || t.to.id === it))); }
  throw new McpError("Unknown tool: " + name);
}
class McpError extends Error {}

async function mcpOne(env, deps, client, msg) {
  const id = msg && msg.id;
  const isNote = !msg || id === undefined || id === null;
  const reply = (result) => ({ jsonrpc: "2.0", id, result });
  const error = (code, message) => ({ jsonrpc: "2.0", id: id === undefined ? null : id, error: { code, message } });
  if (!msg || msg.jsonrpc !== "2.0" || typeof msg.method !== "string") return error(-32600, "Not a JSON-RPC 2.0 request.");
  if (isNote) return null;   // a notification (notifications/initialized and the like): nothing to answer
  const m = msg.method, p = msg.params || {};
  if (m === "initialize") {
    const asked = S(p.protocolVersion);
    return reply({ protocolVersion: MCP_PROTOCOLS.indexOf(asked) >= 0 ? asked : MCP_PROTOCOLS[0], capabilities: { tools: { listChanged: false } }, serverInfo: { name: "safety-lab", title: "Safety Lab", version: API_VERSION }, instructions: MCP_INSTRUCTIONS });
  }
  if (m === "ping") return reply({});
  if (m === "tools/list") return reply({ tools: MCP_TOOLS });
  if (m === "resources/list") return reply({ resources: [] });
  if (m === "prompts/list") return reply({ prompts: [] });
  if (m === "tools/call") {
    const name = S(p.name);
    if (!MCP_TOOLS.some((t) => t.name === name)) return error(-32602, "Unknown tool: " + name);
    try {
      const out = await mcpCall(env, deps, client, name, p.arguments);
      return reply({ content: [{ type: "text", text: JSON.stringify(out) }], structuredContent: out, isError: false });
    } catch (e) {
      if (e instanceof McpError) return reply({ content: [{ type: "text", text: e.message }], isError: true });
      return reply({ content: [{ type: "text", text: "Safety Lab could not answer: " + String((e && e.message) || e) }], isError: true });
    }
  }
  return error(-32601, "Method not found: " + m);
}
async function handleMcp(request, env, deps, client) {
  if (request.method === "GET" || request.method === "DELETE") return fail(405, "method_not_allowed", "This MCP server answers each POST with JSON. It keeps no session and opens no stream.", { allow: "POST" });
  if (request.method !== "POST") return fail(405, "method_not_allowed", "Use POST.", { allow: "POST" });
  const b = await readBody(request); if (b.res) return ok({ jsonrpc: "2.0", id: null, error: { code: -32700, message: "The request body is not valid JSON." } }, 400);
  const body = b.body;
  if (Array.isArray(body)) {
    if (!body.length || body.length > 50) return ok({ jsonrpc: "2.0", id: null, error: { code: -32600, message: "Send 1 to 50 messages in a batch." } }, 400);
    const out = [];
    for (const msg of body) { const r = await mcpOne(env, deps, client, msg); if (r) out.push(r); }
    return out.length ? ok(out) : new Response(null, { status: 202 });
  }
  const r = await mcpOne(env, deps, client, body);
  return r ? ok(r) : new Response(null, { status: 202 });
}

function isApiPath(pathname) {
  return pathname === "/v1/oauth/token" || pathname === "/v1/mcp" || pathname === "/v1/mcp/" || pathname === "/v1/projects" || pathname.startsWith("/v1/projects/");
}


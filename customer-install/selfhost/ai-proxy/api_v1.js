function toolIdOf(clientUuid) { return "api-" + String(clientUuid).replace(/-/g, "").slice(0, 12); }
async function authenticate(request, env, ctx, deps) {
  const auth = request.headers.get("authorization") || "";
  if (!/^Bearer\s+/i.test(auth)) return { res: fail(401, "unauthorized", "Send your access token or personal API key as: Authorization: Bearer <token>.", { "www-authenticate": 'Bearer realm="safety-lab"' }) };
  const token = auth.replace(/^Bearer\s+/i, "").trim();
  let row = null;
  if (/^sla_/.test(token)) {
    const t = await readToken(env, token);
    if (!t || !UUID.test(t.client)) return { res: fail(401, "invalid_token", "This access token is not valid or has expired. Ask for a new one at /v1/oauth/token.") };
    row = arr(await sbJson(deps, env, "/api_clients?id=eq." + enc(t.client) + "&kind=eq.client&select=*"))[0] || null;
  } else if (/^slk_[0-9a-f]{64}$/.test(token)) {
    const hash = await sha256hex(token);
    row = arr(await sbJson(deps, env, "/api_clients?secret_hash=eq." + hash + "&kind=eq.personal&select=*"))[0] || null;
  } else {
    return { res: fail(401, "invalid_token", "That is not a Safety Lab access token (sla_...) or personal API key (slk_...).") };
  }
  if (!row) return { res: fail(401, "invalid_token", "This key is not known to this Safety Lab server.") };
  if (row.revoked_at) return { res: fail(401, "revoked", "This key was revoked. Ask a workspace admin for a new one.") };
  // when it was last used, written at most every five minutes and never in the caller's way
  const last = row.last_used_at ? Date.parse(row.last_used_at) : 0;
  if (!(Date.now() - last < 5 * 60 * 1000)) {
    const p = deps.sbFetch(env, "/api_clients?id=eq." + enc(row.id), { method: "PATCH", headers: { prefer: "return=minimal" }, body: JSON.stringify({ last_used_at: new Date().toISOString() }) }).catch(() => {});
    try { if (ctx && ctx.waitUntil) ctx.waitUntil(p); } catch (_) {}
  }
  return { client: { id: row.id, kind: row.kind, name: row.name, workspace_id: row.workspace_id, can_send: !!row.can_send, project_ids: row.project_ids || null, user_id: row.user_id || null, toolId: toolIdOf(row.id) } };
}

// The projects a key can read, each with whether it may send there.
//   an API client: the projects of its workspace (all of them, or the ones the admin chose)
//   a personal key: what that person can open now (their workspaces as they are today); sending needs an editing role
async function projectsFor(env, deps, client) {
  if (client.kind === "client") {
    let q = "/projects?workspace_id=eq." + enc(client.workspace_id) + "&deleted_at=is.null&select=id,name,cert_basis,workspace_id,updated_at&order=name.asc";
    if (client.project_ids && client.project_ids.length) q += "&id=in.(" + client.project_ids.filter((x) => UUID.test(x)).join(",") + ")";
    else if (client.project_ids) return [];
    return arr(await sbJson(deps, env, q)).map((p) => Object.assign(p, { can_send: client.can_send }));
  }
  const mem = arr(await sbJson(deps, env, "/workspace_members?user_id=eq." + enc(client.user_id) + "&select=workspace_id,role"));
  if (!mem.length) return [];
  const role = {}; mem.forEach((m) => { role[m.workspace_id] = m.role; });
  const ids = Object.keys(role).filter((x) => UUID.test(x));
  const rows = arr(await sbJson(deps, env, "/projects?workspace_id=in.(" + ids.join(",") + ")&deleted_at=is.null&select=id,name,cert_basis,workspace_id,updated_at&order=name.asc"));
  return rows.map((p) => Object.assign(p, { can_send: client.can_send && EDIT_ROLES.indexOf(role[p.workspace_id]) >= 0 }));
}

// ------------------------------------------------------------------ the project document
const _docs = new Map();   // project id -> { version, doc }: the last two documents read, so a run of calls parses each once
async function loadDoc(env, deps, projectId) {
  const head = arr(await sbJson(deps, env, "/project_documents?project_id=eq." + enc(projectId) + "&select=version,updated_at"))[0];
  if (!head) return { version: 0, updated_at: null, doc: {} };
  const hit = _docs.get(projectId);
  if (hit && hit.version === head.version) return { version: head.version, updated_at: head.updated_at, doc: hit.doc };
  const full = arr(await sbJson(deps, env, "/project_documents?project_id=eq." + enc(projectId) + "&select=data,version,updated_at"))[0];
  const doc = (full && full.data && typeof full.data === "object") ? full.data : {};
  _docs.delete(projectId); _docs.set(projectId, { version: full ? full.version : 0, doc });
  while (_docs.size > 2) _docs.delete(_docs.keys().next().value);
  return { version: full ? full.version : 0, updated_at: full ? full.updated_at : null, doc };
}


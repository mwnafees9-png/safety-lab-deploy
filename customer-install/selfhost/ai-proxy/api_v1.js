function page(rows, url) {
  const limit = Math.max(1, Math.min(1000, Number(url.searchParams.get("limit")) || 200));
  const offset = Math.max(0, Number(url.searchParams.get("offset")) || 0);
  const data = rows.slice(offset, offset + limit);
  return { data, total: rows.length, offset, limit, next: offset + limit < rows.length ? offset + limit : null };
}

// ================================================================== collections (what a tool sends)
function cleanItem(raw) {
  // -> { item } or { err }
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return { err: "each item is an object" };
  const id = S(raw.id);
  if (!id || id.length > 200 || /[\u0000-\u001f]/.test(id)) return { err: "an item needs an id of 1 to 200 characters (your tool's own id for it)" };
  const name = S(raw.name), text = raw.text == null ? "" : String(raw.text);
  if (!name && !text.trim()) return { err: "item " + id + " has no name and no text" };
  if (name.length > 2000) return { err: "item " + id + ": the name is longer than 2,000 characters" };
  if (text.length > 100000) return { err: "item " + id + ": the text is longer than 100,000 characters" };
  const key = S(raw.key) || id;
  if (key.length > 200) return { err: "item " + id + ": the key is longer than 200 characters" };
  const parent = raw.parent == null || S(raw.parent) === "" ? null : S(raw.parent);
  if (parent != null && (parent.length > 200 || parent === id)) return { err: "item " + id + ": the parent is not a valid item id" };
  const sort = raw.sort == null ? null : Number(raw.sort);
  if (sort != null && !isFinite(sort)) return { err: "item " + id + ": sort is not a number" };
  return { item: { id, key, name, text, parent, sort } };
}
function itemOut(r) {
  return drop({
    id: r.item_id, key: r.key, name: r.name, text: r.body, parent: r.parent_id, sort: r.sort, origin: r.origin, lastChangedBy: r.changed_by,
    revision: r.rev, modified: r.modified_at, removed: r.removed_at ? true : undefined,
    status: r.origin === "safety-lab" ? undefined : r.status,
    decision: (r.origin !== "safety-lab" && r.status !== "waiting" && r.decided_rev === r.rev) ? drop({ by: r.decided_by, at: r.decided_at, reason: r.decided_why }) : undefined
  });
}
function collectionOut(c) { return { name: c.name, kind: c.kind, title: c.title, updated: c.updated_at }; }

async function getCollection(env, deps, projectId, client, name) {
  return arr(await sbJson(deps, env, "/api_collections?project_id=eq." + enc(projectId) + "&client=eq." + enc(client.id) + "&name=eq." + enc(name) + "&select=*"))[0] || null;
}
async function putCollection(env, deps, projectId, client, name, body) {
  if (!/^[a-z0-9][a-z0-9_-]{0,62}$/.test(name)) return { res: fail(400, "bad_name", "A collection name is lower-case letters, digits, hyphens and underscores, up to 63 characters, starting with a letter or digit.") };
  const kind = S(body && body.kind);
  const cur = await getCollection(env, deps, projectId, client, name);
  if (cur) {
    if (kind && kind !== cur.kind) return { res: fail(409, "kind_is_fixed", "Collection " + name + " holds " + cur.kind + ". What a collection holds cannot change once it is made; make another collection.") };
    if (body && body.title != null && String(body.title).slice(0, 200) !== cur.title) {
      const up = arr(await sbJson(deps, env, "/api_collections?id=eq." + enc(cur.id), { method: "PATCH", headers: { prefer: "return=representation" }, body: JSON.stringify({ title: String(body.title).slice(0, 200), updated_at: new Date().toISOString() }) }))[0];
      return { col: up || cur, made: false };
    }
    return { col: cur, made: false };
  }
  if (KINDS.indexOf(kind) < 0) return { res: fail(400, "bad_kind", "Say what the collection holds: kind is one of " + KINDS.join(", ") + ".") };
  const made = arr(await sbJson(deps, env, "/api_collections", { method: "POST", headers: { prefer: "return=representation" }, body: JSON.stringify({ project_id: projectId, client: client.id, name, kind, title: String((body && body.title) || "").slice(0, 200) }) }))[0];
  return { col: made, made: true };
}
// Write items into a collection. Pure decision first (what changes), then one write.
//   existing: the rows as they are; items: cleaned items; replace: items not listed are marked removed
//   slOwned: Set of item ids an admin made Safety Lab the owner of (from the project)
function planWrite(existing, items, replace, slOwned, nowIso) {
  const by = new Map(existing.map((r) => [r.item_id, r]));
  const rows = [], res = { created: 0, changed: 0, unchanged: 0, restored: 0, removed: 0, refused: [] };
  const seen = new Set();
  let maxSort = existing.reduce((m, r) => Math.max(m, Number(r.sort) || 0), 0);
  items.forEach((it) => {
    seen.add(it.id);
    const cur = by.get(it.id);
    if (!cur) {
      rows.push({ item_id: it.id, key: it.key, name: it.name, body: it.text, parent_id: it.parent, sort: it.sort != null ? it.sort : ++maxSort, origin: "tool", changed_by: "tool", rev: 1, modified_at: nowIso, removed_at: null, status: "waiting", decided_rev: null, decided_at: null, decided_by: null, decided_why: null });
      res.created++; return;
    }
    if (cur.origin === "safety-lab") { res.refused.push({ id: it.id, reason: "Safety Lab made this item and owns it. Change it in Safety Lab." }); return; }
    if (slOwned && slOwned.has(it.id)) { res.refused.push({ id: it.id, reason: "An admin made Safety Lab the owner of this item. Change it in Safety Lab, or ask the admin to give it back." }); return; }
    const same = cur.key === it.key && cur.name === it.name && cur.body === it.text && (cur.parent_id || null) === it.parent && (it.sort == null || Number(cur.sort) === it.sort) && !cur.removed_at;
    if (same) { res.unchanged++; return; }
    const back = !!cur.removed_at;
    rows.push({ item_id: it.id, key: it.key, name: it.name, body: it.text, parent_id: it.parent, sort: it.sort != null ? it.sort : cur.sort, origin: "tool", changed_by: "tool", rev: Number(cur.rev) + 1, modified_at: nowIso, removed_at: null, status: "waiting", decided_rev: null, decided_at: null, decided_by: null, decided_why: null });
    if (back) res.restored++; else res.changed++;
  });
  if (replace) existing.forEach((cur) => {
    if (seen.has(cur.item_id) || cur.removed_at || cur.origin === "safety-lab") return;
    if (slOwned && slOwned.has(cur.item_id)) return;
    rows.push({ item_id: cur.item_id, key: cur.key, name: cur.name, body: cur.body, parent_id: cur.parent_id, sort: cur.sort, origin: cur.origin, changed_by: "tool", rev: Number(cur.rev) + 1, modified_at: nowIso, removed_at: nowIso, status: "waiting", decided_rev: null, decided_at: null, decided_by: null, decided_why: null });
    res.removed++;
  });
  return { rows, res };
}
// The items of one collection an admin made Safety Lab the owner of. In the app a linked item of an API client is
// known as "<collection name>:<item id>" (two collections may use the same ids), under the client's tool id.
function slOwnedIds(doc, toolId, colName) {
  const owners = (doc && doc.projectConfig && doc.projectConfig.connections && doc.projectConfig.connections.owners) || {};
  const out = new Set(), pre = toolId + ":" + colName + ":";
  Object.keys(owners).forEach((k) => { if (owners[k] === "sl" && k.indexOf(pre) === 0) out.add(k.slice(pre.length)); });
  return out;
}
async function allItems(env, deps, colId) {
  const out = [];
  for (let from = 0; from < 100000; from += 1000) {
    const rows = arr(await sbJson(deps, env, "/api_items?collection=eq." + enc(colId) + "&select=*&order=sort.asc,item_id.asc&limit=1000&offset=" + from));
    out.push(...rows);
    if (rows.length < 1000) break;
  }
  return out;
}
async function writeItems(env, deps, project, client, col, rawItems, replace) {
  if (TOOL_KINDS.indexOf(col.kind) < 0) return { res: fail(409, "receives_only", "Collection " + col.name + " holds failure conditions. Failure conditions are made in Safety Lab; this collection only receives what Safety Lab sends.") };
  if (!Array.isArray(rawItems)) return { res: fail(400, "bad_items", "Send { \"items\": [ ... ] }.") };
  if (rawItems.length > MAX_ITEMS_PER_CALL) return { res: fail(413, "too_many", "Send at most " + MAX_ITEMS_PER_CALL + " items in one call.") };
  const items = [], ids = new Set();
  for (let i = 0; i < rawItems.length; i++) {
    const c = cleanItem(rawItems[i]);
    if (c.err) return { res: fail(400, "bad_item", "Item " + (i + 1) + ": " + c.err + ". Nothing was written.") };
    if (ids.has(c.item.id)) return { res: fail(400, "duplicate_id", "The id " + c.item.id + " is in this call twice. Nothing was written.") };
    ids.add(c.item.id); items.push(c.item);
  }
  const existing = await allItems(env, deps, col.id);
  const { doc } = await loadDoc(env, deps, project.id);
  const plan = planWrite(existing, items, !!replace, slOwnedIds(doc, client.toolId, col.name), new Date().toISOString());
  const live = existing.filter((r) => !r.removed_at).length + plan.res.created + plan.res.restored - plan.res.removed;
  if (live > MAX_ITEMS_PER_COLLECTION) return { res: fail(413, "collection_full", "A collection holds at most " + MAX_ITEMS_PER_COLLECTION + " items.") };
  if (plan.rows.length) {
    const rows = plan.rows.map((r) => Object.assign({ collection: col.id }, r));
    for (let i = 0; i < rows.length; i += 500) {
      await sbJson(deps, env, "/api_items?on_conflict=collection,item_id", { method: "POST", headers: { prefer: "resolution=merge-duplicates,return=minimal" }, body: JSON.stringify(rows.slice(i, i + 500)) });
    }
    await sbJson(deps, env, "/api_collections?id=eq." + enc(col.id), { method: "PATCH", headers: { prefer: "return=minimal" }, body: JSON.stringify({ updated_at: new Date().toISOString() }) });
  }
  const staged = plan.res.created + plan.res.changed + plan.res.restored + plan.res.removed;
  return { out: Object.assign({ collection: col.name }, plan.res, { staged, note: staged ? "Staged. Nothing enters the analysis until an engineer accepts these lines in Safety Lab (Connections, Incoming changes) and signs." : "Nothing changed." }) };
}

// ================================================================== the REST routes
async function readBody(request) {
  const text = await request.text();
  if (text.length > MAX_BODY_BYTES) return { res: fail(413, "too_large", "The request is larger than 2 MB. Send it in smaller parts.") };
  if (!text.trim()) return { body: {} };
  try { return { body: JSON.parse(text) }; } catch (_) { return { res: fail(400, "bad_json", "The request body is not valid JSON.") }; }
}
async function handleToken(request, env, deps) {
  if (request.method !== "POST") return fail(405, "method_not_allowed", "Use POST.", { allow: "POST" });
  let id = "", secret = "", grant = "";
  const basic = /^Basic\s+(.+)$/i.exec(request.headers.get("authorization") || "");
  if (basic) { try { const t = atob(basic[1]); const i = t.indexOf(":"); if (i > 0) { id = t.slice(0, i); secret = t.slice(i + 1); } } catch (_) {} }
  const text = await request.text();
  if (text.length > 8192) return fail(413, "too_large", "The request is too large.");
  const ct = (request.headers.get("content-type") || "").toLowerCase();
  if (ct.indexOf("application/json") >= 0) { try { const j = JSON.parse(text || "{}"); grant = S(j.grant_type); id = id || S(j.client_id); secret = secret || S(j.client_secret); } catch (_) { return fail(400, "invalid_request", "The request body is not valid JSON."); } }
  else { const f = new URLSearchParams(text); grant = S(f.get("grant_type")); id = id || S(f.get("client_id")); secret = secret || S(f.get("client_secret")); }
  if (grant && grant !== "client_credentials") return ok({ error: "unsupported_grant_type", error_description: "Use grant_type=client_credentials." }, 400);
  const bad = () => ok({ error: "invalid_client", error_description: "The client ID or secret is not right, or the client was revoked." }, 401);
  if (!/^slc_[0-9a-f]{24}$/.test(id) || !secret) return bad();
  const rl = await deps.checkRateLimit(env, "token:" + id, 30, "api");
  if (!rl.ok) return fail(rl.unavailable ? 503 : 429, rl.unavailable ? "rate_limit_unavailable" : "rate_limited", "Too many sign-ins for this client. Retry in a minute.", { "retry-after": "60" });
  const row = arr(await sbJson(deps, env, "/api_clients?client_id=eq." + enc(id) + "&kind=eq.client&select=id,secret_hash,revoked_at"))[0];
  const hash = await sha256hex(secret);
  if (!row || row.revoked_at || !sameText(hash, row.secret_hash)) return bad();
  return ok({ access_token: await mintToken(env, row.id), token_type: "Bearer", expires_in: TOKEN_TTL_S });
}

async function handleApi(request, env, ctx, url, deps) {
  try {
    if (!env || !env.SUPABASE_URL || !env.SUPABASE_SERVICE_ROLE_KEY) return fail(503, "not_configured", "This Safety Lab server has no database configured, so the API is not available on it.");
    const path = url.pathname.replace(/\/+$/, "");
    if (path === "/v1/oauth/token") return await handleToken(request, env, deps);
    const a = await authenticate(request, env, ctx, deps);
    if (a.res) return a.res;
    const client = a.client;
    const rl = await deps.checkRateLimit(env, "api:" + client.id, 240, "api");
    if (!rl.ok) return fail(rl.unavailable ? 503 : 429, rl.unavailable ? "rate_limit_unavailable" : "rate_limited", "This key is limited to 240 requests a minute. Retry shortly.", { "retry-after": "60" });
    if (path === "/v1/mcp") return await handleMcp(request, env, deps, client);
    const seg = path.split("/").slice(2).map((s) => { try { return decodeURIComponent(s); } catch (_) { return s; } });   // ["projects", id, ...]
    if (seg[0] !== "projects") return fail(404, "not_found", "Unknown endpoint.");
    const projects = await projectsFor(env, deps, client);
    if (seg.length === 1) {
      if (request.method !== "GET") return fail(405, "method_not_allowed", "Use GET.", { allow: "GET" });
      return ok(page(projects.map((p) => drop({ id: p.id, name: p.name, certificationBasis: p.cert_basis, updated: p.updated_at, canSend: p.can_send })), url));
    }
    const project = projects.filter((p) => p.id === seg[1])[0];
    // a project this key cannot reach is answered exactly like one that does not exist
    if (!UUID.test(S(seg[1])) || !project) return fail(404, "not_found", "No project with that id is open to this key.");
    const meta = (d) => ({ id: project.id, name: project.name, version: d.version, updated: d.updated_at });

    if (seg.length === 2) {
      if (request.method !== "GET") return fail(405, "method_not_allowed", "Use GET.", { allow: "GET" });
      const d = await loadDoc(env, deps, project.id);
      return ok(Object.assign(meta(d), { canSend: project.can_send }, viewSummary(d.doc), { name: project.name }));
    }
    const what = seg[2];
    if (VIEWS[what] && seg.length === 3) {
      if (request.method !== "GET") return fail(405, "method_not_allowed", "Use GET. To send items, write them to a collection: /v1/projects/{project}/collections/{name}/items.", { allow: "GET" });
      const d = await loadDoc(env, deps, project.id);
      return ok(Object.assign({ project: meta(d) }, page(VIEWS[what](d.doc, url.searchParams.get("scope")), url)));
    }
    if (what === "fault-trees" && seg.length === 4) {
      if (request.method !== "GET") return fail(405, "method_not_allowed", "Use GET. Fault trees are made by Safety Lab's engine and cannot be written.", { allow: "GET" });
      const d = await loadDoc(env, deps, project.id);
      const t = viewFaultTree(d.doc, seg[3], url.searchParams.get("depth"));
      if (!t) return fail(404, "not_found", "No fault tree with that id in this project.");
      return ok(Object.assign({ project: meta(d) }, t));
    }
    if (what !== "collections") return fail(404, "not_found", "Unknown endpoint.");

    // ---- collections: this client's own lists of items in the project
    if (seg.length === 3) {
      if (request.method !== "GET") return fail(405, "method_not_allowed", "Use GET here, and PUT /collections/{name} to make one.", { allow: "GET" });
      const cols = arr(await sbJson(deps, env, "/api_collections?project_id=eq." + enc(project.id) + "&client=eq." + enc(client.id) + "&select=*&order=name.asc"));
      return ok({ data: cols.map(collectionOut) });
    }
    const name = seg[3];
    const writing = request.method !== "GET";
    if (writing && !project.can_send) return fail(403, "read_only", "This key reads but does not send. Ask a workspace admin for a key that can send.");
    if (seg.length === 4) {
      if (request.method === "GET") { const c = await getCollection(env, deps, project.id, client, name); return c ? ok(collectionOut(c)) : fail(404, "not_found", "No collection " + name + " for this key in this project."); }
      if (request.method !== "PUT") return fail(405, "method_not_allowed", "Use GET or PUT.", { allow: "GET, PUT" });
      const b = await readBody(request); if (b.res) return b.res;
      const r = await putCollection(env, deps, project.id, client, name, b.body); if (r.res) return r.res;
      return ok(collectionOut(r.col), r.made ? 201 : 200);
    }
    if (seg[4] !== "items") return fail(404, "not_found", "Unknown endpoint.");
    const col = await getCollection(env, deps, project.id, client, name);
    if (!col) return fail(404, "not_found", "No collection " + name + " for this key in this project. Make it first: PUT /v1/projects/{project}/collections/" + name + " with { \"kind\": \"functions\" | \"requirements\" | \"assumptions\" }.");
    if (seg.length === 5) {
      if (request.method === "GET") {
        const rows = await allItems(env, deps, col.id);
        const keep = url.searchParams.get("removed") === "1" ? rows : rows.filter((r) => !r.removed_at);
        return ok(Object.assign({ collection: collectionOut(col) }, page(keep.map(itemOut), url)));
      }
      if (request.method !== "POST") return fail(405, "method_not_allowed", "Use GET or POST.", { allow: "GET, POST" });
      const b = await readBody(request); if (b.res) return b.res;
      const w = await writeItems(env, deps, project, client, col, b.body && b.body.items, !!(b.body && b.body.replace)); if (w.res) return w.res;
      return ok(w.out, w.out.refused.length && !w.out.staged ? 409 : 200);
    }
    if (seg.length === 6) {
      const id = seg[5];
      if (request.method === "GET") {
        const row = arr(await sbJson(deps, env, "/api_items?collection=eq." + enc(col.id) + "&item_id=eq." + enc(id) + "&select=*"))[0];
        return row ? ok(itemOut(row)) : fail(404, "not_found", "No item " + id + " in " + name + ".");
      }
      if (request.method === "PUT") {
        const b = await readBody(request); if (b.res) return b.res;
        const w = await writeItems(env, deps, project, client, col, [Object.assign({}, b.body, { id })], false); if (w.res) return w.res;
        if (w.out.refused.length) return fail(409, "owned_by_safety_lab", w.out.refused[0].reason);
        return ok(w.out, w.out.created ? 201 : 200);
      }
      if (request.method === "DELETE") {
        if (TOOL_KINDS.indexOf(col.kind) < 0) return fail(409, "receives_only", "This collection only receives what Safety Lab sends.");
        const row = arr(await sbJson(deps, env, "/api_items?collection=eq." + enc(col.id) + "&item_id=eq." + enc(id) + "&select=*"))[0];
        if (!row) return fail(404, "not_found", "No item " + id + " in " + name + ".");
        if (row.origin === "safety-lab") return fail(409, "owned_by_safety_lab", "Safety Lab made this item and owns it.");
        const { doc } = await loadDoc(env, deps, project.id);
        if (slOwnedIds(doc, client.toolId, col.name).has(id)) return fail(409, "owned_by_safety_lab", "An admin made Safety Lab the owner of this item.");
        if (!row.removed_at) {
          const now = new Date().toISOString();
          await sbJson(deps, env, "/api_items?collection=eq." + enc(col.id) + "&item_id=eq." + enc(id), { method: "PATCH", headers: { prefer: "return=minimal" }, body: JSON.stringify({ removed_at: now, modified_at: now, rev: Number(row.rev) + 1, changed_by: "tool", status: "waiting", decided_rev: null, decided_at: null, decided_by: null, decided_why: null }) });
        }
        return ok({ collection: col.name, removed: row.removed_at ? 0 : 1, staged: row.removed_at ? 0 : 1, note: "Marked removed. Safety Lab never deletes on a tool's word: the item is flagged as missing for an engineer." });
      }
      return fail(405, "method_not_allowed", "Use GET, PUT or DELETE.", { allow: "GET, PUT, DELETE" });
    }
    return fail(404, "not_found", "Unknown endpoint.");
  } catch (e) {
    if (e && e.status && e.status >= 500) return fail(502, "upstream_down", "The Safety Lab database could not be reached. Retry shortly.");
    return fail(500, "api_exception", String((e && e.message) || e));
  }
}


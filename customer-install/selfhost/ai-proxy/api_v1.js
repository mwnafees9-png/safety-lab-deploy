// Who owns a row: the tool it is linked to, unless an admin made Safety Lab the owner of that item.
function ownerOf(doc, src) {
  if (!src || !src.tool || src.remoteId == null) return { owner: "safety-lab" };
  const tool = String(src.tool) === "jama-live" ? "jama" : String(src.tool);
  const owners = (doc.projectConfig && doc.projectConfig.connections && doc.projectConfig.connections.owners) || {};
  const out = { owner: owners[tool + ":" + src.remoteId] === "sl" ? "safety-lab" : tool, source: { tool, id: String(src.remoteId) } };
  if (S(src.key)) out.source.key = S(src.key);
  if (src.missingInSource) out.source.missing = true;
  return out;
}
function systemsOf(doc) { return arr(doc.systemsData).filter((s) => s && s.id != null); }
function scopeList(doc, scope) {
  // scope: undefined/"all" -> the aircraft and every system; "aircraft"; a system id
  const all = [{ id: "aircraft", name: "Aircraft", sys: null }].concat(systemsOf(doc).map((s) => ({ id: String(s.id), name: S(s.name), sys: s })));
  const want = S(scope).toLowerCase();
  if (!want || want === "all") return all;
  return all.filter((x) => x.id.toLowerCase() === want);
}
const drop = (o) => { Object.keys(o).forEach((k) => { if (o[k] === undefined || o[k] === null || o[k] === "" || (Array.isArray(o[k]) && !o[k].length)) delete o[k]; }); return o; };
const list = (v) => (Array.isArray(v) ? v.map(S).filter(Boolean) : S(v).split(/\s*,\s*/).filter(Boolean));

function viewFunctions(doc, scope) {
  const out = [];
  scopeList(doc, scope).forEach((sc) => {
    if (!sc.sys) {
      const seen = new Set();
      arr(doc.acFunctionsData).forEach((r) => {
        if (!r) return;
        const o = ownerOf(doc, r.fnSource);
        const fid = S(r.funcId);
        if (fid && !seen.has(fid)) {
          seen.add(fid);
          out.push(drop({ id: fid, name: S(r.funcName), description: S(r.funcDef), level: 1, scope: "aircraft", ...(r.fnSource && r.fnSource.funcOnly ? o : { owner: o.owner }) }));
        }
        if (S(r.subId)) out.push(drop({ id: S(r.subId), name: S(r.subName), description: S(r.subDef), parent: S(r.parentSubId) || fid, level: S(r.parentSubId) ? 3 : 2, scope: "aircraft", ...o }));
      });
      // a sub-function under another sub-function sits one level below its parent, however deep
      const by = new Map(out.filter((x) => x.scope === "aircraft").map((x) => [x.id, x]));
      out.forEach((x) => { if (x.scope !== "aircraft" || !x.parent) return; let d = 1, cur = x, g = 0; while (cur && cur.parent && g++ < 50) { d++; cur = by.get(cur.parent); } x.level = d; });
    } else {
      arr(sc.sys.functions).forEach((r) => {
        if (!r || !S(r.funcId)) return;
        out.push(drop({ id: S(r.funcId), name: S(r.funcName), description: S(r.funcDef), scope: sc.id, system: sc.name, traces: list(r.traceIds), ...ownerOf(doc, r.fnSource) }));
      });
    }
  });
  return out;
}

function viewFailureConditions(doc, scope) {
  const acById = new Map(arr(doc.acFhaData).filter(Boolean).map((r) => [String(r.internalId), S(r.fcId)]));
  const out = [];
  scopeList(doc, scope).forEach((sc) => {
    const rows = sc.sys ? arr(sc.sys.fha) : arr(doc.acFhaData);
    rows.forEach((r) => {
      if (!r || !S(r.fcId)) return;
      const fns = list(r.subIds).length ? list(r.subIds) : list(r.subId);
      const up = arr(r.acTraces).length ? arr(r.acTraces) : (r.acTrace != null ? [r.acTrace] : []);
      out.push(drop({
        id: S(r.fcId), description: S(r.fcDesc), severity: S(r.severity), function: fns[0], functions: fns.length > 1 ? fns : undefined,
        phases: list(r.phases), effects: drop({ aircraft: S(r.effAc), crew: S(r.effCrew), occupants: S(r.effPax) }),
        assumptions: list(r.assumptionIds), scope: sc.id, system: sc.sys ? sc.name : undefined,
        aircraftFailureConditions: sc.sys ? up.map((x) => acById.get(String(x))).filter(Boolean) : undefined,
        ...ownerOf(doc, r.fcSource)
      }));
    });
  });
  return out;
}

function viewRequirements(doc, scope) {
  const out = [];
  scopeList(doc, scope).forEach((sc) => {
    const rows = sc.sys ? arr(sc.sys.req) : arr(doc.acReqData);
    rows.forEach((r) => {
      if (!r || !S(r.text)) return;
      const tr = list(r.traceIds).length ? list(r.traceIds) : list(r.traceId);
      out.push(drop({
        id: S(r.id) || ("REQ-" + S(r.internalId)), text: S(r.text), type: S(r.type), level: S(r.level), rationale: S(r.rat),
        verification: drop({ method: S(r.verifMethod), status: S(r.verifStatus), evidence: S(r.verifEvidence) }),
        traces: tr, scope: sc.id, system: sc.sys ? sc.name : undefined, ...ownerOf(doc, r.reqSource)
      }));
    });
  });
  return out;
}


// ------------------------------------------------------------------ crypto
function b64u(bytes) {
  let s = "";
  const b = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  for (let i = 0; i < b.length; i++) s += String.fromCharCode(b[i]);
  return btoa(s).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}
function b64uText(str) { return b64u(new TextEncoder().encode(str)); }
function unb64u(str) {
  const s = String(str).replace(/-/g, "+").replace(/_/g, "/");
  const bin = atob(s + "=".repeat((4 - (s.length % 4)) % 4));
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}
async function sha256hex(text) {
  const b = new Uint8Array(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(String(text))));
  let hex = "";
  for (let i = 0; i < b.length; i++) hex += b[i].toString(16).padStart(2, "0");
  return hex;
}
// two strings of the same length compared without stopping at the first difference
function sameText(a, b) {
  a = String(a); b = String(b);
  if (a.length !== b.length) return false;
  let d = 0;
  for (let i = 0; i < a.length; i++) d |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return d === 0;
}
// The key access tokens are signed with: derived from the server's own database key, so an install needs no new
// secret and a token made on one server means nothing on another.
async function tokenKey(env) {
  const root = await crypto.subtle.importKey("raw", new TextEncoder().encode(String(env.SUPABASE_SERVICE_ROLE_KEY)), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  const derived = await crypto.subtle.sign("HMAC", root, new TextEncoder().encode("safety-lab-api-token-v1"));
  return crypto.subtle.importKey("raw", derived, { name: "HMAC", hash: "SHA-256" }, false, ["sign", "verify"]);
}
async function mintToken(env, clientUuid, nowMs = Date.now(), ttlS = TOKEN_TTL_S) {
  const body = b64uText(JSON.stringify({ c: clientUuid, e: Math.floor(nowMs / 1000) + ttlS }));
  const sig = await crypto.subtle.sign("HMAC", await tokenKey(env), new TextEncoder().encode(body));
  return "sla_" + body + "." + b64u(sig);
}
async function readToken(env, token, nowMs = Date.now()) {
  try {
    const m = /^sla_([A-Za-z0-9_-]+)\.([A-Za-z0-9_-]+)$/.exec(String(token));
    if (!m) return null;
    const good = await crypto.subtle.verify("HMAC", await tokenKey(env), unb64u(m[2]), new TextEncoder().encode(m[1]));
    if (!good) return null;
    const p = JSON.parse(new TextDecoder().decode(unb64u(m[1])));
    if (!p || typeof p.c !== "string" || !(Number(p.e) > nowMs / 1000)) return null;
    return { client: p.c, exp: Number(p.e) };
  } catch (_) { return null; }
}

// ------------------------------------------------------------------ the database (service role, through deps.sbFetch)
async function sbJson(deps, env, path, opts) {
  const res = await deps.sbFetch(env, path, opts);
  const text = await res.text();
  let data = null;
  try { data = text ? JSON.parse(text) : null; } catch (_) { data = null; }
  if (!res.ok) { const e = new Error("database " + res.status + (data && data.message ? ": " + data.message : "")); e.status = res.status; e.db = data; throw e; }
  return data;
}
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;


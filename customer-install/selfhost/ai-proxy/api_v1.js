//
// Waqas, 27 Nov 2026: "API and MCP yes". The contract is the connections deck: two ways to sign in (an API client
// for a system, a personal API key for a person's scripts); read the whole project (functions, failure conditions,
// fault trees, requirements, assumptions and their traces); "what a tool sends arrives as lines an engineer accepts
// and signs. Items another tool owns cannot be changed. No special cases." MCP: an AI assistant reads through the
// same gate and can propose; "fault trees and requirements are generated by Safety Lab's deterministic engine".
//
// HOW WRITING WORKS. Nothing here ever writes a project. A tool keeps its own items in named collections
// (api_collections, api_items). In the app each API client is a connected tool on the Connections page: a check
// reads its collections and stages every difference as a line, and nothing enters the analysis until an engineer
// accepts the line and signs. A client writes only its own collections, so it cannot touch an item another tool
// owns. What it removes is marked removed, never deleted; the app flags it as missing.
//
// WHERE IT RUNS. Imported by worker.js: the same file on our cloud (api.safetylabaero.com) and on a customer's
// own server (customer-install/selfhost/ai-proxy, kept byte-identical; a test compares them).
//
//   POST /v1/oauth/token                               client credentials -> a one-hour access token
//   GET  /v1/projects                                  the projects this key can read
//   GET  /v1/projects/{project}                        name, version, counts
//   GET  /v1/projects/{project}/functions | failure-conditions | requirements | assumptions | fault-trees | traces
//   GET  /v1/projects/{project}/fault-trees/{tree}     one tree, nested
//   GET  /v1/projects/{project}/collections            this client's collections in the project
//   PUT  /v1/projects/{project}/collections/{name}     make one ({ kind, title })
//   GET  /v1/projects/{project}/collections/{name}/items             its items, each with where it stands
//   POST /v1/projects/{project}/collections/{name}/items             many items ({ items: [...], replace })
//   PUT  /v1/projects/{project}/collections/{name}/items/{id}        one item
//   DELETE /v1/projects/{project}/collections/{name}/items/{id}      mark one removed
//   POST /v1/mcp                                       the MCP server (Streamable HTTP, JSON answers)
